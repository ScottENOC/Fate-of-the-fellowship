'use strict';
const fs=require('node:fs');
const p='index.html';
let s=fs.readFileSync(p,'utf8');
const old="  #game{position:relative;display:flex;flex-direction:column;height:100dvh}";
const neu="  #game{position:relative;flex-direction:column;height:100dvh}";
if(!s.includes(old)) throw new Error('portrait game rule anchor missing');
s=s.replace(old,neu);
fs.writeFileSync(p,s);
const t='tests/index-syntax.cjs';
let q=fs.readFileSync(t,'utf8');
const marker="console.log('index inline script syntax: ok');";
if(!q.includes(marker)) throw new Error('syntax marker missing');
q=q.replace(marker,`const html = fs.readFileSync(path.join(__dirname, '..', 'index.html'), 'utf8');\nconst portraitBlock = html.match(/@media \\(orientation:portrait\\)\\{([\\s\\S]*?)\\n\\}/)?.[1] || '';\nif (/#[g]ame\\s*\\{[^}]*display\\s*:\\s*flex/.test(portraitBlock)) throw new Error('portrait CSS must not force #game visible before start');\n${marker}`);
fs.writeFileSync(t,q);
